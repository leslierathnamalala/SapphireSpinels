export function getGem(id) {
  return GEMS.find((gem) => gem.id === id) ?? null;
}

export function catalogBounds() {
  const prices = GEMS.map((gem) => gem.price);
  const carats = GEMS.map((gem) => gem.carat);
  return {
    priceMin: Math.min(...prices),
    priceMax: Math.max(...prices),
    caratMin: Math.min(...carats),
    caratMax: Math.max(...carats),
  };
}

export function facetOptions() {
  const unique = (key) => [...new Set(GEMS.map((gem) => gem[key]))];
  return {
    sizes: SIZES.filter((size) => unique('size').includes(size)),
    shapes: unique('shape').sort((a, b) => a.localeCompare(b)),
    gemstones: unique('gemstone').sort((a, b) => a.localeCompare(b)),
    types: TYPES.filter((type) => unique('type').includes(type)),
    families: FAMILY_ORDER.filter((family) => unique('family').includes(family)),
  };
}
